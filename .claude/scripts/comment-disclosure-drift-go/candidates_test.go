// The artifact CLASS comes from the permalink path too: a PR's conversation, review and inline
// comments all live under /pull/<n>, an issue's under /issues/<n>.
func TestCandidates_ClassComesFromThePermalinkPath(t *testing.T) {
	cases := []struct {
		name, record, prefix string
	}{
		{"pr conversation", `{"user":{"login":"devantler"},"body":"do not merge","created_at":"2026-09-01T00:00:00Z","html_url":"https://github.com/devantler-tech/monorepo/pull/42#issuecomment-1","issue_url":"https://api.github.com/repos/devantler-tech/monorepo/issues/42"}`, "CANDIDATE-MAINTAINER-COMMENT monorepo #42 — "},
		{"pr review body", `{"user":{"login":"devantler"},"body":"redesign this","submitted_at":"2026-09-01T00:00:01Z","html_url":"https://github.com/devantler-tech/monorepo/pull/42#pullrequestreview-7","pull_request_url":"https://api.github.com/repos/devantler-tech/monorepo/pulls/42"}`, "CANDIDATE-MAINTAINER-COMMENT monorepo #42 — "},
		{"pr inline", `{"user":{"login":"devantler"},"body":"wrong call","created_at":"2026-09-01T00:00:02Z","html_url":"https://github.com/devantler-tech/monorepo/pull/42#discussion_r9","pull_request_url":"https://api.github.com/repos/devantler-tech/monorepo/pulls/42"}`, "CANDIDATE-MAINTAINER-COMMENT monorepo #42 — "},
		{"issue", `{"user":{"login":"devantler"},"body":"please split this","created_at":"2026-09-01T00:00:03Z","html_url":"https://github.com/devantler-tech/monorepo/issues/43#issuecomment-2","issue_url":"https://api.github.com/repos/devantler-tech/monorepo/issues/43"}`, "CANDIDATE-MAINTAINER-ISSUE-COMMENT monorepo #43 — "},
	}
	for _, tc := range cases {
		scan := scanPayload(t, "["+tc.record+"]")
		if len(scan.Rows) != 1 || !strings.HasPrefix(scan.Rows[0].String(), tc.prefix) {
			t.Errorf("%s: got %+v, want prefix %q", tc.name, scan.Rows, tc.prefix)
		}
	}
}

// Disclosed agent output is skipped whatever the actor word; a sender-marker body is the
// sibling's undisclosed output; merely MENTIONING an agent never demotes a comment.
func TestCandidates_DisclosureAndSenderMarkerGate(t *testing.T) {
	url := func(id string) string {
		return `"https://github.com/devantler-tech/monorepo/issues/7#issuecomment-` + id + `"`
	}
	payload := `[` +
		`{"author":{"login":"devantler"},"body":"> 🤖 Generated by the Daily AI Assistant\n\nold","url":` + url("1") + `},` +
		`{"author":{"login":"devantler"},"body":"> 🤖 Generated by the Agentic Engineer\n\n@coderabbitai review please","url":` + url("2") + `},` +
		`{"author":{"login":"devantler"},"body":"> Requested by the 🤖 Daily AI Engineer — CI is green","url":` + url("3") + `},` +
		`{"author":{"login":"devantler"},"body":"The last Codex agent run missed X; do Y.","url":` + url("4") + `}` +
		`]`
	scan := scanPayload(t, payload)
	if scan.Disclosed != 2 {
		t.Fatalf("disclosed: got %d, want 2", scan.Disclosed)
	}
	if len(scan.Rows) != 2 {
		t.Fatalf("want two rows, got %+v", scan.Rows)
	}
	if got := scan.Rows[0].String(); !strings.HasPrefix(got, "CANDIDATE-SIBLING-ISSUE-COMMENT monorepo #7 (missing disclosure) — ") {
		t.Errorf("sender marker: %s", got)
	}
	if got := scan.Rows[1].String(); !strings.HasPrefix(got, "CANDIDATE-MAINTAINER-ISSUE-COMMENT monorepo #7 — ") {
		t.Errorf("mention must stay a maintainer candidate: %s", got)
	}
	sibling := `[{"user":{"login":"devantler"},"body":"🤖 Sent by the Agentic Engineer","html_url":"https://github.com/devantler-tech/monorepo/pull/8#issuecomment-1"}]`
	if got := scanPayload(t, sibling).Rows[0].String(); !strings.HasPrefix(got, "CANDIDATE-SIBLING-COMMENT monorepo #8 (missing disclosure) — ") {
		t.Errorf("PR sibling: %s", got)
	}
}

// Other authors are never candidates but are counted, and every considered record lands in
// exactly one bucket, so the closing line always adds up.
func TestCandidates_SummaryAccountsForEveryRecord(t *testing.T) {
	payload := `[` + issue3239Bot + `,` + issue3239Disclosed + `,` + issue3275Real + `,` +
		`{"user":{"login":"devantler"},"body":"  \n","submitted_at":"2026-09-01T00:00:00Z","html_url":"https://github.com/devantler-tech/platform/pull/9#pullrequestreview-1","pull_request_url":"https://api.github.com/repos/devantler-tech/platform/pulls/9"}` +
		`]`
	scan := scanPayload(t, payload)
	want := "CANDIDATE-SCAN author=devantler records=4 considered=3 disclosed=1 maintainer=1 sibling=0 empty=1 artifacts=platform#3239,platform#3275,platform#9"
	if got := scan.Summary(); got != want {
		t.Fatalf("summary:\n got %s\nwant %s", got, want)
	}
}

