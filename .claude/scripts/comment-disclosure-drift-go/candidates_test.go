// The 2026-09-02 misattribution (monorepo#3163): the surveyor reported a real undisclosed
// `devantler` comment that lives on platform#3275 under platform#3239, an issue whose
// `devantler` comments are all disclosed. The orchestrator checked #3239, found nothing and
// discarded the finding. The fixtures keep the real URL shapes; the bodies are synthetic.
const (
	issue3239Disclosed = `{"author":{"login":"devantler"},"body":"> 🤖 Generated by the Agentic Engineer\n\nStatus note.","createdAt":"2026-08-29T18:23:09Z","url":"https://github.com/devantler-tech/platform/issues/3239#issuecomment-5337878100"}`
	issue3239Bot       = `{"author":{"login":"coderabbitai"},"body":"Summary by CodeRabbit","createdAt":"2026-08-19T05:21:55Z","url":"https://github.com/devantler-tech/platform/issues/3239#issuecomment-5337878167"}`
	issue3275Real      = `{"author":{"login":"devantler"},"body":"The merged scanner upgrade removed the local-mode abort.\n\nSecond paragraph.","createdAt":"2026-08-28T19:51:48Z","url":"https://github.com/devantler-tech/platform/issues/3275#issuecomment-5457089789"}`
)

func scanPayload(t *testing.T, payload string) CandidateScan {
	t.Helper()
	records, err := DecodeCandidatePayload([]byte(payload))
	if err != nil {
		t.Fatalf("decode: %v", err)
	}
	return ScanCandidates(records, "devantler")
}

// The row's number is a function of the comment's OWN url, so a payload that interleaves two
// issues cannot carry one issue's number onto the other's comment.
func TestCandidates_RowNumberComesFromTheCommentItself(t *testing.T) {
	payload := "[" + issue3239Bot + "," + issue3239Disclosed + "," + issue3275Real + "]"
	scan := scanPayload(t, payload)
	if len(scan.Rows) != 1 {
		t.Fatalf("want exactly one candidate, got %d: %+v", len(scan.Rows), scan.Rows)
	}
	row := scan.Rows[0].String()
	want := "CANDIDATE-MAINTAINER-ISSUE-COMMENT platform #3275 — `devantler` @2026-08-28T19:51:48Z: " +
		`"The merged scanner upgrade removed the local-mode abort." ` +
		"https://github.com/devantler-tech/platform/issues/3275#issuecomment-5457089789"
	if row != want {
		t.Fatalf("row:\n got %s\nwant %s", row, want)
	}
	if strings.Contains(row, "3239") {
		t.Fatalf("row names the neighbouring issue: %s", row)
	}
	if got := scan.Summary(); !strings.Contains(got, "artifacts=platform#3239,platform#3275") {
		t.Fatalf("summary must list every artifact the payload covered: %s", got)
	}
}

