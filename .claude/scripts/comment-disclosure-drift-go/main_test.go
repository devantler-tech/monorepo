// The live sample the issue cited, as a regression corpus. Kept as JSON so it
// round-trips through the same decode path production uses.
func TestAnalyse_LiveSampleCorpus(t *testing.T) {
	corpus := []map[string]any{
		// world-at-ruin#661 5150876600 -- trailing disclosure
		{"id": 5150876600, "author": "devantler",
			"body": "@coderabbitai full review\n\n> 🤖 Generated by the Agentic Engineer."},
		// world-at-ruin#662 5151295297 -- annotated trigger, no disclosure at all
		{"id": 5151295297, "author": "devantler",
			"body": "@coderabbitai review\n\nPlease review exact head 94171a33ec112cf86f559f037bf99a54fe996a43"},
		// ksail#6244 5030838223 -- non-canonical sender marker
		{"id": 5030838223, "author": "devantler",
			"body": "> Requested by the 🤖 Daily AI Engineer — CI is green at the current head."},
		// ksail#6244 5030838309 -- the bare-trigger carve-out, must NOT be flagged
		{"id": 5030838309, "author": "devantler", "body": "@cursor review"},
		// a correctly-formed comment, must NOT be flagged
		{"id": 9999999999, "author": "devantler",
			"body": "> 🤖 Generated by the Agentic Engineer\n\n## Why\n\nReal work.\n"},
	}
	raw, err := json.Marshal(corpus)
	if err != nil {
		t.Fatalf("marshal corpus: %v", err)
	}
	comments, err := decode(raw)
	if err != nil {
		t.Fatalf("decode corpus: %v", err)
	}
	report := Analyse(comments, "devantler")

	// The bare @cursor review at 5030838309 follows a SENDER-MARKER comment, not a
	// canonical disclosure, so its exemption is unpaired and it is reported too.
	if len(report.Findings) != 4 {
		t.Fatalf("findings = %d, want 4", len(report.Findings))
	}
	wantVerdicts := map[int64]Verdict{
		5030838223: SenderMarker,
		5030838309: UndisclosedTrigger,
		5150876600: UndisclosedTrigger,
		5151295297: UndisclosedTrigger,
	}
	for _, finding := range report.Findings {
		want, ok := wantVerdicts[finding.ID]
		if !ok {
			t.Errorf("unexpected finding on comment %d (%q)", finding.ID, finding.Verdict)
			continue
		}
		if finding.Verdict != want {
			t.Errorf("comment %d: verdict %q, want %q", finding.ID, finding.Verdict, want)
		}
	}
	if report.Counts[BareTrigger] != 0 {
		t.Errorf("bare-trigger count = %d, want 0 (the trigger is unpaired)", report.Counts[BareTrigger])
	}
	if report.Counts[Compliant] != 1 {
		t.Errorf("compliant count = %d, want 1", report.Counts[Compliant])
	}
	// Findings must be ID-ordered so the report is stable run to run.
	for i := 1; i < len(report.Findings); i++ {
		if report.Findings[i-1].ID >= report.Findings[i].ID {
			t.Fatalf("findings are not ID-ordered: %+v", report.Findings)
		}
	}
}

// Codex P1 (#2720): the Bugbot carve-out is conditional on the disclosure sitting
// in its own comment IMMEDIATELY BEFORE the trigger. Judged per-body in isolation,
// an unpaired bare trigger cleared the guard -- exactly the case the contract
// excludes.
func TestAnalyse_BareTriggerNeedsItsPrecedingDisclosure(t *testing.T) {
	paired := []Comment{
		{ID: 1, Author: "devantler", Body: "> 🤖 Generated by the Agentic Engineer\n\nRequesting a review."},
		{ID: 2, Author: "devantler", Body: "@cursor review"},
	}
	if report := Analyse(paired, "devantler"); len(report.Findings) != 0 {
		t.Errorf("paired trigger reported: %+v", report.Findings)
	}

	unpaired := []Comment{{ID: 1, Author: "devantler", Body: "@cursor review"}}
	report := Analyse(unpaired, "devantler")
	if len(report.Findings) != 1 || report.Findings[0].Verdict != UndisclosedTrigger {
		t.Errorf("unpaired trigger: findings = %+v, want one undisclosed-trigger", report.Findings)
	}

	// Preceded by a NON-disclosure comment is still unpaired.
	wrongNeighbour := []Comment{
		{ID: 1, Author: "devantler", Body: "> Requested by the 🤖 Daily AI Engineer - CI is green"},
		{ID: 2, Author: "devantler", Body: "@cursor review"},
	}
	if report := Analyse(wrongNeighbour, "devantler"); len(report.Findings) != 2 {
		t.Errorf("wrong-neighbour pairing: findings = %+v, want both reported", report.Findings)
	}

	// A comment from another login is skipped BEFORE the pairing state is updated, so
	// it does not break an otherwise valid disclosure/trigger pair. That ordering is
	// deliberate: anyone may comment between the two, and letting a stranger's remark
	// turn our own compliant pair into a violation would report the wrong party. This
	// pins the ordering, so moving the SkippedAuthors branch below the assignment
	// fails here instead of silently changing who gets reported.
	interleaved := []Comment{
		{ID: 1, Author: "devantler", Body: "> 🤖 Generated by the Agentic Engineer\n\nRequesting a review."},
		{ID: 2, Author: "someone-else", Body: "looks good to me"},
		{ID: 3, Author: "devantler", Body: "@cursor review"},
	}
	if report := Analyse(interleaved, "devantler"); len(report.Findings) != 0 {
		t.Errorf("interleaved foreign comment broke the pairing: %+v", report.Findings)
	}
}

