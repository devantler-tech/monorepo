// The canonical form, as the lanes emit it today.
const compliantBody = "> 🤖 Generated by the Agentic Engineer\n\n## Why\n\nSomething.\n"

func TestClassify_CanonicalPrefixIsCompliant(t *testing.T) {
	if got := Classify(compliantBody); got != Compliant {
		t.Fatalf("canonical leading disclosure: got %q, want %q", got, Compliant)
	}
}

// The actor word has been renamed twice. A matcher keyed to one spelling would
// silently reclassify every comment written under the others, so every historical
// form must stay compliant -- permanently.
func TestClassify_EveryHistoricalActorWordStaysCompliant(t *testing.T) {
	actors := []string{
		"Agentic Engineer",
		"Agentic Engineer (Cursor cloud instance)",
		"Daily AI Engineer",
		"Daily AI Assistant",
		"Some Future Role Nobody Has Named Yet",
	}
	for _, actor := range actors {
		body := "> 🤖 Generated by the " + actor + "\n\nBody.\n"
		if got := Classify(body); got != Compliant {
			t.Errorf("actor %q: got %q, want %q", actor, got, Compliant)
		}
	}
}

// Shape A, measured live on world-at-ruin#661 comment 5150876600: the body opens
// with a review trigger and closes with the disclosure.
func TestClassify_TrailingDisclosureIsAViolation(t *testing.T) {
	body := "@coderabbitai full review\n\nPlease review exact head abc123.\n\n> 🤖 Generated by the Agentic Engineer.\n"
	if got := Classify(body); got != TrailingDisclosure {
		t.Fatalf("trailing disclosure: got %q, want %q", got, TrailingDisclosure)
	}
}

// Codex P1 (#2720): a disclosure in the MIDDLE of the body must NOT be reported.
// That is the maintainer's ordinary "Quote reply" shape -- he quotes the agent and
// then writes his response underneath, so his own text is last. Reporting it would
// flag the control channel, the one direction this guard must never fail in.
func TestClassify_MidBodyDisclosureIsNotAViolation(t *testing.T) {
	body := "Some preamble.\n\n> 🤖 Generated by the Agentic Engineer\n\nMore text after it.\n"
	if got := Classify(body); got.violating() {
		t.Fatalf("mid-body disclosure: got violation %q, want a non-violating verdict", got)
	}
}

// Codex P1 (#2720): the SINGLE-level quote is the normal GitHub "Quote reply"
// shape and previously produced an exit 1 on the maintainer's own comment. The
// nested "> >" form was already covered; this is the common one.
func TestClassify_SingleLevelQuoteReplyIsNotAViolation(t *testing.T) {
	bodies := []string{
		// He quotes the agent, then answers underneath.
		"> 🤖 Generated by the Agentic Engineer\n> I decided to do X\n\nNo, do Y instead.\n",
		// He quotes a multi-line block whose LAST line is the disclosure.
		"Disagree.\n\n> I decided to do X\n> 🤖 Generated by the Agentic Engineer\n",
		// Quote-only reply, no trailing disclosure.
		"> 🤖 Generated by the Agentic Engineer\n> I decided to do X\n",
	}
	for _, body := range bodies {
		if got := Classify(body); got.violating() {
			t.Errorf("single-level quote reply %q: got violation %q", excerpt(body, 46), got)
		}
	}
}

