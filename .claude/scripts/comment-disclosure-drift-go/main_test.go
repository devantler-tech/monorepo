// Codex P1 (#2720): Bugbot exact-matches the literal body, so a variant that would
// NOT fire the lane has no claim to the exemption -- exempting it would hide a
// disclosure violation on a comment that also silently started no review.
// Asserting only "not exempted" would pass while a variant went unreported, so each
// variant pins the verdict it actually earns. The double-spaced body is the one that
// earns no violation: it matches no trigger shape, so the guard has no POSITIVE
// evidence that an agent authored it. That residual is deliberate -- reporting a
// merely trigger-ish body would be the absence-based test this guard rejects, which
// flags the maintainer's own comments -- so it is pinned as a known non-violating
// case rather than quietly satisfying a weaker assertion.
func TestClassify_BugbotExemptionIsByteExact(t *testing.T) {
	want := map[string]Verdict{
		"@Cursor Review":        UndisclosedTrigger,
		"@cursor  review":       Unattributable,
		"@cursor review please": UndisclosedTrigger,
		"  @cursor review  ":    UndisclosedTrigger,
		"@cursor review\n":      UndisclosedTrigger,
		"\n@cursor review":      UndisclosedTrigger,
	}
	for body, expected := range want {
		got := Classify(body)
		if got == BareTrigger {
			t.Errorf("%q was exempted; the exemption is byte-exact", body)
		}
		if got != expected {
			t.Errorf("%q: got %q, want %q", body, got, expected)
		}
	}
}

