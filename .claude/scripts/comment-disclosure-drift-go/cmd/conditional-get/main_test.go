// fixture models GitHub's changed and conditional list responses for the real wrapper.
func fixture(t *testing.T) (string, string, string) {
	t.Helper()
	_, file, _, _ := runtime.Caller(0)
	wrapper := filepath.Clean(filepath.Join(filepath.Dir(file), "..", "..", "..", "comment-disclosure-drift.sh"))
	dir := t.TempDir()
	bin := filepath.Join(dir, "bin")
	if err := os.Mkdir(bin, 0700); err != nil {
		t.Fatal(err)
	}
	stub := `#!/usr/bin/env bash
set -euo pipefail
endpoint=""; include=0; validator=""
for argument in "$@"; do
 case "$argument" in
  --include) include=1 ;;
  repos/*) endpoint=$argument ;;
  "If-None-Match: "*) validator=${argument#If-None-Match: } ;;
 esac
done
[ -n "$endpoint" ] || exit 9
printf '%s\n' "$endpoint" >> "$FIXTURE_CALLS"
case "$endpoint" in
 *"/pulls?"*) body='[{"number":7,"updated_at":"2026-10-12T20:00:00Z"}]' ;;
 *"/pulls/7/reviews"*) body='[{"id":3,"body":"> 🤖 Generated by the Agentic Engineer\\nreview","user":{"login":"devantler"},"submitted_at":"2026-10-12T20:00:00Z"}]' ;;
 *"/pulls/comments?"*) body='[]' ;;
 *"/issues/comments?"*) body='[{"id":1,"body":"> 🤖 Generated by the Agentic Engineer\\ncomment","user":{"login":"devantler"},"issue_url":"https://api.github.com/repos/owner/repo/issues/1"}]' ;;
 *) exit 9 ;;
esac
tag='"fixture-1"'
if [ "$FIXTURE_MODE" = changed ] && [[ "$endpoint" == *"/issues/comments?"* ]]; then
 tag='"fixture-2"'
 body='[{"id":1,"body":"@coderabbitai review","user":{"login":"devantler"},"issue_url":"https://api.github.com/repos/owner/repo/issues/1"}]'
fi
if [ "$include" = 1 ] && [ "$validator" = "$tag" ] && [ "$FIXTURE_MODE" != failed ]; then
 printf 'HTTP/2.0 304 Not Modified\r\nETag: %s\r\n\r\n' "$tag"
 exit 1
fi
printf 'charged\n' >> "$FIXTURE_CHARGED"
if [ "$include" = 1 ]; then printf 'HTTP/2.0 200 OK\r\nETag: %s\r\n\r\n' "$tag"; fi
printf '%s\n' "$body"
if [ "$FIXTURE_MODE" = failed ]; then exit 17; fi
`
	if err := os.WriteFile(filepath.Join(bin, "gh"), []byte(stub), 0700); err != nil {
		t.Fatal(err)
	}
	return wrapper, dir, bin
}

// invoke executes the actual Bash wrapper with an isolated fake forge and private cache.
func invoke(t *testing.T, wrapper, dir, bin, mode string) (int, string) {
	t.Helper()
	cmd := exec.Command("bash", wrapper, "--repo", "owner/repo", "--since", "2026-10-12T00:00:00Z")
	cmd.Env = append(os.Environ(),
		"PATH="+bin+string(os.PathListSeparator)+os.Getenv("PATH"),
		"DISCLOSURE_API_CACHE_DIR="+filepath.Join(dir, "cache"),
		"FIXTURE_CALLS="+filepath.Join(dir, "calls"),
		"FIXTURE_CHARGED="+filepath.Join(dir, "charged"),
		"FIXTURE_MODE="+mode)
	// The wrapper's existing classifier suite recursively tests this package.
	// An integration run builds binaries only; it does not invoke go test.
	output, err := cmd.CombinedOutput()
	if err == nil {
		return 0, string(output)
	}
	if exit, ok := err.(*exec.ExitError); ok {
		return exit.ExitCode(), string(output)
	}
	t.Fatal(err)
	return -1, ""
}

// charged counts full source responses rather than all conditional requests.
func charged(t *testing.T, dir string) int {
	t.Helper()
	bytes, err := os.ReadFile(filepath.Join(dir, "charged"))
	if err != nil {
		t.Fatal(err)
	}
	return len(strings.Fields(string(bytes)))
}

// TestWrapperConfirmsUnchangedPagesWithoutSpendingAgain proves the repeat sweep's budget reduction.
func TestWrapperConfirmsUnchangedPagesWithoutSpendingAgain(t *testing.T) {
	wrapper, dir, bin := fixture(t)
	for run := 0; run < 2; run++ {
		code, out := invoke(t, wrapper, dir, bin, "clean")
		if code != 0 {
			t.Fatalf("run %d exit %d: %s", run, code, out)
		}
	}
	if got := charged(t, dir); got != 4 {
		t.Fatalf("unchanged second sweep charged again: got %d source responses, want 4 cold responses only", got)
	}
}

// TestWrapperRefreshesFindingsAndPreservesProducerFailure preserves changed and failed-read verdicts.
func TestWrapperRefreshesFindingsAndPreservesProducerFailure(t *testing.T) {
	wrapper, dir, bin := fixture(t)
	if code, out := invoke(t, wrapper, dir, bin, "clean"); code != 0 {
		t.Fatalf("cold: %d %s", code, out)
	}
	if code, out := invoke(t, wrapper, dir, bin, "changed"); code != 1 || !strings.Contains(out, "undisclosed-trigger") {
		t.Fatalf("changed source: %d %s", code, out)
	}
	if code, out := invoke(t, wrapper, dir, bin, "failed"); code != 2 {
		t.Fatalf("failed producer: %d %s", code, out)
	}
}
