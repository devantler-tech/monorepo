#!/usr/bin/env bash
# Behaviour tests for pr-body-contract.sh: the three safety rules (monorepo#5049) and the seed path.

# shellcheck disable=SC2016 # Backticks in fixture bodies are literal Markdown, never substitutions.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
subject="${repo_root}/.claude/scripts/pr-body-contract.sh"
workflow="${repo_root}/.github/workflows/ci.yaml"
fixture_root="$(mktemp -d)"
test_run_finished=0
# bash 3.2 can report a set -e abort inside an EXIT trap as exit 0, so require completion.
on_test_exit() {
  local status=$?
  rm -rf "${fixture_root}"
  if [ "${test_run_finished}" != 1 ]; then
    echo "pr-body-contract.test.sh: aborted before finishing; reporting failure rather than a clean pass" >&2
    [ "${status}" != 0 ] || status=1
    exit "${status}"
  fi
}
trap on_test_exit EXIT

fail() {
  echo "pr-body contract test: FAIL — $*" >&2
  exit 1
}

expect_ok() {
  local name="$1"
  shift
  if ! "$@" >"${fixture_root}/stdout" 2>"${fixture_root}/stderr"; then
    cat "${fixture_root}/stderr" >&2
    fail "${name} should pass"
  fi
}

# The expected text must appear in stderr, so a negative control fails for the right reason.
expect_fail() {
  local name="$1"
  local expected="$2"
  shift 2
  if "$@" >"${fixture_root}/stdout" 2>"${fixture_root}/stderr"; then
    fail "${name} should fail"
  fi
  grep -Fq -- "${expected}" "${fixture_root}/stderr" || {
    cat "${fixture_root}/stderr" >&2
    fail "${name} did not report '${expected}'"
  }
}

[ -x "${subject}" ] || fail "subject is missing or not executable: ${subject}"

# check makes no GitHub request: a gh that always fails proves it.
mkdir -p "${fixture_root}/bin"
cat >"${fixture_root}/bin/gh" <<'EOF'
#!/usr/bin/env bash
case "${GH_MODE:-fail}" in
  repo)
    case "$*" in
      'api repos/devantler-tech/platform --jq .full_name') echo 'devantler-tech/platform' ;;
      'api repos/upstream/project --jq .full_name') echo 'upstream/project' ;;
      *'contents/.github --jq'*) echo 'PULL_REQUEST_TEMPLATE.md' ;;
      *'contents/.github/PULL_REQUEST_TEMPLATE.md'*) printf '## Why\n\n## What\n\nFixes #\n' ;;
      *) echo 'gh: Not Found (HTTP 404)' >&2; exit 1 ;;
    esac
    ;;
  *) echo 'gh: unexpected call' >&2; exit 1 ;;
esac
EOF
chmod +x "${fixture_root}/bin/gh"

run_check() {
  local body="$1"
  shift
  PATH="${fixture_root}/bin:${PATH}" "${subject}" check --repo devantler-tech/platform \
    --body-file "${body}" "$@"
}

write_body() {
  local name="$1"
  shift
  printf '%s\n' "$@" >"${fixture_root}/${name}.md"
  printf '%s' "${fixture_root}/${name}.md"
}

good="$(write_body good \
  '> 🤖 Generated by the Agentic Engineer' '' \
  '<!-- Template comments may stay. -->' '' \
  '## Why' '' 'Reviewers lose time on style rules.' '' \
  '## What' '' '- Keeps the three safety checks; see https://github.com/devantler-tech/monorepo and ci.yaml.' \
  '- Version 1.2.3, e.g. a 1.5x speedup, served from 8.8.8.8 and devantler.tech.' \
  '' '| Style | Now free |' '|---|---|' '| tables | yes |' '' \
  'Fixes #5049')"
expect_ok "a body with free style passes" run_check "${good}"
expect_ok "stdin input passes" bash -c \
  "PATH='${fixture_root}/bin:${PATH}' '${subject}' check --repo devantler-tech/platform --body-file - <'${good}'"
expect_ok "the improver role passes with its own disclosure" run_check \
  "$(write_body improver '> 🤖 Generated by the Agent Improver' '' 'Part of #12')" --role agent-improver
expect_ok "one Fixes and a distinct Part of may pair" run_check \
  "$(write_body pair '> 🤖 Generated by the Agentic Engineer' '' 'Fixes #1' 'Part of #2')"
expect_ok "the trivial-fix carve-out passes with its flag" run_check \
  "$(write_body trivial '> 🤖 Generated by the Agentic Engineer' '' 'No issue: trivial fix.')" --allow-no-issue

# Rule 1: disclosure.
expect_fail "a missing disclosure" "first-line disclosure does not match" run_check \
  "$(write_body nodisc '## Why' '' 'Fixes #1')"
expect_fail "the wrong role's disclosure" "first-line disclosure does not match --role agent-improver" \
  run_check "${good}" --role agent-improver
expect_fail "a second disclosure" "exactly one routine-role disclosure" run_check \
  "$(write_body twodisc '> 🤖 Generated by the Agentic Engineer' '' '> 🤖 Generated by the Agent Improver' '' 'Fixes #1')"
: >"${fixture_root}/empty.md"
expect_fail "a zero-byte body" "body is empty" run_check "${fixture_root}/empty.md"

# Rule 2: exactly one issue relationship.
expect_fail "no relationship" "exactly one issue relationship" run_check \
  "$(write_body norel '> 🤖 Generated by the Agentic Engineer' '' 'Text.')"
expect_fail "an unresolved placeholder" "unresolved issue placeholder" run_check \
  "$(write_body placeholder '> 🤖 Generated by the Agentic Engineer' '' 'Fixes #')"
expect_fail "two Fixes lines" "exactly one issue relationship" run_check \
  "$(write_body twofix '> 🤖 Generated by the Agentic Engineer' '' 'Fixes #1' 'Fixes #2')"
expect_fail "a second closing keyword in prose" "permitted shape" run_check \
  "$(write_body proseclose '> 🤖 Generated by the Agentic Engineer' '' 'This also closes #9.' '' 'Fixes #1')"
expect_fail "a cross-repository closing keyword" "permitted shape" run_check \
  "$(write_body crossclose '> 🤖 Generated by the Agentic Engineer' '' 'Resolves devantler-tech/ksail#9' '' 'Fixes #1')"
expect_fail "pairing an issue with itself" "must be distinct" run_check \
  "$(write_body samepair '> 🤖 Generated by the Agentic Engineer' '' 'Fixes #3' 'Part of #3')"
expect_fail "the trivial-fix marker without its flag" "exactly one issue relationship" run_check \
  "${fixture_root}/trivial.md"
expect_fail "the flag without the marker" "requires the explicit trivial-fix marker" run_check \
  "$(write_body flagonly '> 🤖 Generated by the Agentic Engineer' '' 'Text.')" --allow-no-issue
expect_fail "the trivial-fix marker beside a relationship" "cannot accompany" run_check \
  "$(write_body both '> 🤖 Generated by the Agentic Engineer' '' 'No issue: trivial fix.' 'Fixes #1')"

# Rule 3: no non-public host or private address, anywhere in the raw body.
for case_line in \
  'nas.lan|Served from nas.lan now.' \
  'grafana.internal|See https://grafana.internal/d/x for the panel.' \
  'build.corp|Linked [here](http://build.corp:8080).' \
  'host.home.arpa|Reachable at host.home.arpa.' \
  'ops.example-lab|Mail ops@ops.example-lab.' \
  '192.168.1.20|Gateway 192.168.1.20 answers.' \
  '10.0.4.7|Pod 10.0.4.7 answers.' \
  '172.20.0.1|Bridge 172.20.0.1 answers.' \
  '100.64.0.9|Tailnet 100.64.0.9 answers.' \
  'db.local|<!-- leftover note: db.local -->'; do
  expected="${case_line%%|*}"
  body="$(write_body host '> 🤖 Generated by the Agentic Engineer' '' "${case_line#*|}" '' 'Fixes #1')"
  expect_fail "the non-public host ${expected}" "(matched: ${expected})" run_check "${body}"
done
expect_fail "uppercase does not hide a host" "(matched: nas.lan)" run_check \
  "$(write_body upper '> 🤖 Generated by the Agentic Engineer' '' 'NAS.LAN is down.' '' 'Fixes #1')"
expect_fail "a public address range boundary stays private" "(matched: 172.31.255.255)" run_check \
  "$(write_body edge '> 🤖 Generated by the Agentic Engineer' '' 'Edge 172.31.255.255.' '' 'Fixes #1')"
expect_ok "a neighbouring public range is not private" run_check \
  "$(write_body pub '> 🤖 Generated by the Agentic Engineer' '' 'Edge 172.32.0.1 and 100.128.0.1.' '' 'Fixes #1')"

# Code spans and fences hold code, not hosts: identifiers pass, private names still do not.
expect_ok "code identifiers in backticks pass" run_check "$(write_body codeok '> 🤖 Generated by the Agentic Engineer' '' \
  'Uses `fmt.Errorf`, `github.event.pull_request.body` and `index.html`.' '' '```' 'cfg.Spec.Name' '```' '' 'Fixes #1')"
for case_line in \
  'db.lan|Code `db.lan` here.' \
  'nas.example-lab|Code `http://nas.example-lab:8080/x`.' \
  'grafana.internal|```|curl http://grafana.internal/x|```'; do
  expected="${case_line%%|*}"
  rest="${case_line#*|}"
  IFS='|' read -r -a lines <<<"${rest}"
  body="$(write_body codehost '> 🤖 Generated by the Agentic Engineer' '' "${lines[@]}" '' 'Fixes #1')"
  expect_fail "the private host ${expected} inside code" "(matched: ${expected})" run_check "${body}"
done
# A private address behind a host-style prefix is still an address.
expect_fail "a prefixed private address" "(matched: node-192.168.1.20)" run_check \
  "$(write_body prefixed '> 🤖 Generated by the Agentic Engineer' '' 'Host node-192.168.1.20 down.' '' 'Fixes #1')"
# GitHub also closes on the KEYWORD: #N form.
expect_fail "a colon closing keyword" "permitted shape" run_check \
  "$(write_body colonclose '> 🤖 Generated by the Agentic Engineer' '' 'Also Closes: #13 later.' '' 'Fixes #1')"

# A missing or empty TLD list is UNKNOWN, never a clean pass.
cp "${subject}" "${fixture_root}/pr-body-contract.sh"
cp "${repo_root}/.claude/scripts/markdown-structural-lines.awk" "${fixture_root}/"
expect_fail "a missing TLD list" "public TLD evidence is missing" \
  "${fixture_root}/pr-body-contract.sh" check --repo devantler-tech/platform --body-file "${good}"
printf '# comment only\n' >"${fixture_root}/pr-body-public-tlds.txt"
set +e
"${fixture_root}/pr-body-contract.sh" check --repo devantler-tech/platform --body-file "${good}" \
  >/dev/null 2>"${fixture_root}/stderr"
status=$?
set -e
if [ "${status}" -ne 2 ] || ! grep -Fq 'public TLD evidence is empty' "${fixture_root}/stderr"; then
  fail "an empty TLD list must report UNKNOWN (exit 2), got ${status}"
fi

# Third-party targets: only the host rule applies.
external="$(write_body external 'Plain upstream body with no disclosure and no issue.')"
expect_ok "a third-party body needs no disclosure or relationship" env PATH="${fixture_root}/bin:${PATH}" \
  "${subject}" check --repo upstream/project --body-file "${external}"
expect_fail "a third-party body still may not name a private host" "(matched: nas.lan)" \
  env PATH="${fixture_root}/bin:${PATH}" "${subject}" check --repo upstream/project \
  --body-file "$(write_body external-host 'Tested against nas.lan.')"

# Usage errors are UNKNOWN.
set +e
"${subject}" check --repo not-a-repo --body-file "${good}" >/dev/null 2>&1
[ $? -eq 1 ] || fail "a malformed --repo must be refused"
"${subject}" check --repo devantler-tech/platform --body-file "${good}" --role other >/dev/null 2>&1
[ $? -eq 1 ] || fail "an unknown role must be refused"
"${subject}" >/dev/null 2>&1
[ $? -eq 2 ] || fail "a missing command must be a usage error"
set -e

# seed prepends the role disclosure for the portfolio and preserves a third-party template.
expect_ok "seed for a portfolio repository" env PATH="${fixture_root}/bin:${PATH}" GH_MODE=repo \
  "${subject}" seed --repo devantler-tech/platform --output "${fixture_root}/seeded.md" --role agent-improver
[ "$(head -n 1 "${fixture_root}/seeded.md")" = '> 🤖 Generated by the Agent Improver' ] ||
  fail "seed did not prepend the role disclosure"
grep -Fqx '## Why' "${fixture_root}/seeded.md" || fail "seed did not copy the template"
expect_ok "seed for a third-party repository" env PATH="${fixture_root}/bin:${PATH}" GH_MODE=repo \
  "${subject}" seed --repo upstream/project --output "${fixture_root}/seeded-external.md"
[ "$(head -n 1 "${fixture_root}/seeded-external.md")" = '## Why' ] ||
  fail "seed must not attribute a third-party body"
expect_fail "seed refuses to overwrite" "refusing to overwrite" env PATH="${fixture_root}/bin:${PATH}" \
  GH_MODE=repo "${subject}" seed --repo devantler-tech/platform --output "${fixture_root}/seeded.md"
expect_fail "seed fails closed when no template exists" "lookup" env PATH="${fixture_root}/bin:${PATH}" \
  GH_MODE=fail "${subject}" seed --repo devantler-tech/platform --output "${fixture_root}/none.md"

# CI keeps enforcing the published routine-role body.
grep -Fq 'bash .claude/scripts/pr-body-contract.sh check' "${workflow}" ||
  fail "required CI no longer enforces the routine-role PR body contract"

test_run_finished=1
echo "pr-body-contract.test.sh: PASS"
