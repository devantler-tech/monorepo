#!/usr/bin/env bash

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
subject="${repo_root}/.claude/scripts/pr-body-contract.sh"
contract="${repo_root}/AGENTS.md"
maintenance_overlay="${repo_root}/.claude/skills/portfolio-maintenance/SKILL.md"
engineering_overlay="${repo_root}/.claude/skills/product-engineering/SKILL.md"
workflow="${repo_root}/.github/workflows/ci.yaml"
fixture_root="$(mktemp -d)"
trap 'rm -rf "${fixture_root}"' EXIT

fail() {
  echo "pr-body contract test: FAIL — $*" >&2
  exit 1
}

expect_ok() {
  local name="$1"
  shift
  if ! "$@" >"${fixture_root}/stdout" 2>"${fixture_root}/stderr"; then
    cat "${fixture_root}/stderr" >&2
    fail "${name} should pass"
  fi
}

expect_fail() {
  local name="$1"
  local expected="$2"
  shift 2
  if "$@" >"${fixture_root}/stdout" 2>"${fixture_root}/stderr"; then
    fail "${name} should fail"
  fi
  grep -Fq "${expected}" "${fixture_root}/stderr" || {
    cat "${fixture_root}/stderr" >&2
    fail "${name} did not report '${expected}'"
  }
}

[ -x "${subject}" ] || fail "subject is missing or not executable: ${subject}"

for authoring_surface in "${contract}" "${maintenance_overlay}" "${engineering_overlay}"; do
  grep -Fq '.claude/scripts/pr-body-contract.sh seed' "${authoring_surface}" ||
    fail "${authoring_surface#"${repo_root}/"} does not require seeding from the effective GitHub template"
  grep -Fq '.claude/scripts/pr-body-contract.sh check' "${authoring_surface}" ||
    fail "${authoring_surface#"${repo_root}/"} does not require validating the completed body"
done
grep -Fq 'read the published body back' "${contract}" ||
  fail "AGENTS.md does not require validation of GitHub's published body"
grep -Fq 'Before every Agentic Engineer or Agent Improver PR creation or body edit' "${contract}" ||
  fail "AGENTS.md does not scope the executable write gate to its supported routine roles"
grep -Fq -- '--allow-no-issue' "${contract}" ||
  fail "AGENTS.md does not bind the no-issue flag to the documented trivial-fix carve-out"
if grep -Fq 'Before every agent-authored PR creation or body edit' "${contract}"; then
  fail "AGENTS.md incorrectly applies the routine-role disclosure gate to interactive PRs"
fi
grep -Fq "'.claude/scripts/pr-body-contract.sh'" "${workflow}" ||
  fail "CI change detection does not include the PR-body guard"
grep -Fq "'.claude/scripts/pr-body-contract.test.sh'" "${workflow}" ||
  fail "CI change detection does not include the PR-body regression test"
grep -Fq 'bash .claude/scripts/pr-body-contract.test.sh' "${workflow}" ||
  fail "CI does not execute the PR-body regression test"
grep -Fq 'Enforce the routine-role PR body contract' "${workflow}" ||
  fail "required CI does not validate the published routine-role PR body"
grep -Fq 'types: [opened, synchronize, reopened, edited, ready_for_review]' "${workflow}" ||
  fail "required CI does not rerun for body edits and draft promotion"
grep -Fq "if: github.event.pull_request.head.repo.full_name == github.repository" "${workflow}" ||
  fail "the routine-role body check is not fenced to trusted same-repository code"
grep -Fq 'bash .claude/scripts/pr-body-contract.sh check' "${workflow}" ||
  fail "required CI does not invoke the PR-body contract against the event body"
# The candidate workflow must pass the runtime shell variable literally.
# shellcheck disable=SC2016
grep -Fq -- '--role "${role}"' "${workflow}" ||
  fail "required CI does not pass the role selected from the disclosure"
grep -Fq "'> 🤖 Generated by the Agentic Engineer') role='agentic-engineer'" "${workflow}" ||
  fail "required CI does not map the engineer disclosure to its contract role"
grep -Fq "'> 🤖 Generated by the Agent Improver') role='agent-improver'" "${workflow}" ||
  fail "required CI does not map the improver disclosure to its contract role"
grep -Fq "'> 🤖 Generated by the Daily AI Engineer') role='agentic-engineer'" "${workflow}" ||
  fail "required CI does not route the legacy engineer disclosure through body hygiene"
grep -Fq "'> 🤖 Generated by the Daily AI Assistant') role='agentic-engineer'" "${workflow}" ||
  fail "required CI does not route the legacy assistant disclosure through body hygiene"
grep -Fq "Generated by the (Agentic Engineer|Daily AI Engineer|Daily AI Assistant)[[:space:]]*$'" \
  "${workflow}" || fail "required CI does not detect a displaced routine-role disclosure"
grep -Fq "grep -Eq '^[[:space:]]*>[[:space:]]*🤖 Generated by the Agent Improver[[:space:]]*$'" \
  "${workflow}" || fail "required CI does not route an indented routine-role disclosure"
grep -Fq "contract_args+=(--allow-no-issue)" "${workflow}" ||
  fail "required CI does not preserve the explicit trivial-fix carve-out"
grep -Fq -- '- guard-pr-body-marker-collision' "${workflow}" ||
  fail "the routine-role PR-body guard is absent from the required status aggregate"

