#!/usr/bin/env bash
set -euo pipefail

not_found() {
  echo 'gh: Not Found (HTTP 404)' >&2
  exit 1
}

case "${GH_MODE:-}" in
  repo)
    case "$*" in
      *'repos/devantler-tech/platform/contents/.github/PULL_REQUEST_TEMPLATE.md'*)
        cat "${GH_TEMPLATE_FIXTURE}"
        ;;
      *'repos/devantler-tech/platform/contents/.github --jq'*)
        echo 'PULL_REQUEST_TEMPLATE.md'
        ;;
      *) not_found ;;
    esac
    ;;
  org)
    case "$*" in
      *'repos/devantler-tech/platform/contents/'*) not_found ;;
      *'repos/devantler-tech/.github/contents/.github/PULL_REQUEST_TEMPLATE.md'*)
        cat "${GH_TEMPLATE_FIXTURE}"
        ;;
      *'repos/devantler-tech/.github/contents/.github --jq'*)
        echo 'PULL_REQUEST_TEMPLATE.md'
        ;;
      *) not_found ;;
    esac
    ;;
  org-root)
    case "$*" in
      *'repos/devantler-tech/platform/contents/'*) not_found ;;
      *'repos/devantler-tech/.github/contents/PULL_REQUEST_TEMPLATE.md'*)
        cat "${GH_TEMPLATE_FIXTURE}"
        ;;
      *'repos/devantler-tech/.github/contents --jq'*)
        echo 'PULL_REQUEST_TEMPLATE.md'
        ;;
      *) not_found ;;
    esac
    ;;
  token)
    [ "${GH_TOKEN:-}" = 'fixture-token' ] || exit 1
    case "$*" in
      *'repos/devantler-tech/platform/contents/.github/PULL_REQUEST_TEMPLATE.md'*)
        cat "${GH_TEMPLATE_FIXTURE}"
        ;;
      *'repos/devantler-tech/platform/contents/.github --jq'*)
        echo 'PULL_REQUEST_TEMPLATE.md'
        ;;
      *) not_found ;;
    esac
    ;;
  authfail)
    case "$*" in
      *'repos/devantler-tech/platform/contents/.github --jq'*)
        echo 'gh: Resource not accessible by integration (HTTP 403)' >&2
        exit 1
        ;;
      *'repos/devantler-tech/.github/contents/.github/PULL_REQUEST_TEMPLATE.md'*)
        cat "${GH_TEMPLATE_FIXTURE}"
        ;;
      *)
        echo 'gh: Not Found (HTTP 404)' >&2
        exit 1
        ;;
    esac
    ;;
  mixedcase)
    case "$*" in
      *'repos/devantler-tech/platform/contents --jq'*)
        echo 'Pull_Request_Template.txt'
        ;;
      *'repos/devantler-tech/platform/contents/Pull_Request_Template.txt'*)
        cat "${GH_TEMPLATE_FIXTURE}"
        ;;
      *) not_found ;;
    esac
    ;;
  none) not_found ;;
  *) exit 2 ;;
esac
