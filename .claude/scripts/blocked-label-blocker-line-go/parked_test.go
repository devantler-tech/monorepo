const (
	goodLine   = "**Blocker:** owner/repo#7 | upstream | last-verified 2026-09-01: open"
	recordHead = "> 🤖 Generated by the Agentic Engineer\n\n" + recordMarker + "\n"
)

func commentJSON(t *testing.T, login, body string) string {
	t.Helper()
	raw, err := json.Marshal(map[string]any{"user": map[string]string{"login": login}, "body": body})
	if err != nil {
		t.Fatal(err)
	}
	return string(raw)
}

// parkedPull is an --input pull request carrying the blocked label and the
// given comments. Its body declares a different blocker, which must never be
// read: the record of a pull request is its comment.
func parkedPull(comments ...string) string {
	return `[{"repo":"p","number":5,"pull_request":{},"labels":[{"name":"blocked"}],"body":"**Blocker:** body/only#1","comments":[` + strings.Join(comments, ",") + `]}]`
}

func TestParkedPullRequestIsJudgedByItsOneRecordComment(t *testing.T) {
	record := commentJSON(t, "devantler", recordHead+goodLine)
	for _, tc := range []struct {
		name     string
		comments []string
		code     int
		want     string
	}{
		{"one conforming record", []string{record}, 0, "all 1 open blocked-labelled pull request(s) carry one conforming record comment"},
		{"the record among unrelated comments", []string{commentJSON(t, "devantler", "> 🤖 Generated by the Agentic Engineer\n\nStatus."), record, commentJSON(t, "someone", "thanks")}, 0, "all 1 open"},
		{"no comment at all", nil, 1, "MISSING    p#5  [pull request]"},
		{"a blocker line without the marker", []string{commentJSON(t, "devantler", "> 🤖 Generated by the Agentic Engineer\n\n"+goodLine)}, 1, "MISSING    p#5  [pull request]"},
		{"the marker only inside a code fence", []string{commentJSON(t, "devantler", "> 🤖 Generated by the Agentic Engineer\n\n```\n"+recordMarker+"\n```\n"+goodLine)}, 1, "MISSING    p#5  [pull request]"},
		{"the marker inside other text", []string{commentJSON(t, "devantler", "> 🤖 Generated by the Agentic Engineer\n\nsee "+recordMarker+" here\n"+goodLine)}, 1, "MISSING    p#5  [pull request]"},
		{"a record from another author", []string{commentJSON(t, "someone", recordHead+goodLine)}, 1, "MISSING    p#5  [pull request]"},
		{"a record from an author whose name only starts the same", []string{commentJSON(t, "devantler-bot", recordHead+goodLine)}, 1, "MISSING    p#5  [pull request]"},
		{"a record without the disclosure line first", []string{commentJSON(t, "devantler", recordMarker+"\n"+goodLine)}, 1, "MISSING    p#5  [pull request]"},
		{"a record comment with no blocker line", []string{commentJSON(t, "devantler", recordHead+"nothing here")}, 1, "MISSING    p#5  [pull request]"},
		{"two record comments", []string{record, record}, 1, "DUPLICATE  p#5  [pull request]"},
		{"a malformed line", []string{commentJSON(t, "devantler", recordHead+"**Blocker:** owner/repo#7")}, 1, "MALFORMED  p#5  [pull request]  >>**Blocker:** owner/repo#7"},
		{"an authority blocker nobody was asked about", []string{commentJSON(t, "devantler", recordHead+"**Blocker:** approve the upgrade | authority | last-verified 2026-09-01: waiting")}, 1, "NO-ASK     p#5  [pull request]"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			code, out := runInput(t, parkedPull(tc.comments...))
			if code != tc.code || !strings.Contains(out, tc.want) {
				t.Fatalf("code=%d, want %d and %q; out:\n%s", code, tc.code, tc.want, out)
			}
			if strings.Contains(out, "body/only") || strings.Contains(out, "UNLABELLED") {
				t.Fatalf("the pull request's body was read as a record; out:\n%s", out)
			}
			if tc.code == 1 && !strings.Contains(out, "1 of 1 open blocked-labelled pull request(s) need repair") {
				t.Fatalf("no pull-request summary; out:\n%s", out)
			}
		})
	}
}

// The label is what parks a pull request. Without it nothing is judged,
// whatever the comments say, so an unlabelled pull request is always worked.
func TestUnlabelledPullRequestIsNotParked(t *testing.T) {
	for name, labels := range map[string]string{"an empty label set": `"labels":[],`, "another label": `"labels":[{"name":"dependencies"}],`, "no labels array": ""} {
		t.Run(name, func(t *testing.T) {
			code, out := runInput(t, `[{"repo":"p","number":5,"pull_request":{},`+labels+`"body":"x","comments":[`+commentJSON(t, "devantler", recordHead+"**Blocker:** broken")+`]}]`)
			if code != 0 || !strings.Contains(out, "all 0 open blocked-labelled pull request(s)") {
				t.Fatalf("code=%d out:\n%s", code, out)
			}
		})
	}
}

func TestParkedPullRequestRecordGoesStale(t *testing.T) {
	payload := parkedPull(commentJSON(t, "devantler", recordHead+goodLine))
	if code, out := runInput(t, payload, "--today", "2026-09-09", "--verify-max-age-days", "7"); code != 1 || !strings.Contains(out, "STALE      p#5  [pull request]") {
		t.Fatalf("code=%d out:\n%s", code, out)
	}
	// CONTROL: the same record on the last day inside the bound conforms.
	if code, out := runInput(t, payload, "--today", "2026-09-08", "--verify-max-age-days", "7"); code != 0 {
		t.Fatalf("code=%d out:\n%s", code, out)
	}
}

