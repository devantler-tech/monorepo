// The repository name reaches a forge path, so only a plain name is used.
func TestCommentEndpointRefusesAnUnusableRepository(t *testing.T) {
	for _, repo := range []string{"", ".", "..", "a/b", "a b", "a?b", "a#b", "a%2Fb"} {
		if endpoint, err := commentEndpoint("o", repo, 1); err == nil {
			t.Errorf("repo %q produced %q", repo, endpoint)
		}
	}
	if endpoint, err := commentEndpoint("o", ".github", 12); err != nil || endpoint != "repos/o/.github/issues/12/comments?per_page=100" {
		t.Errorf("endpoint=%q err=%v", endpoint, err)
	}
}

