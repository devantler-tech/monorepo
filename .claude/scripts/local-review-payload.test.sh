#!/usr/bin/env bash
# local-review-payload.test.sh — round-trip proof for local-review-payload.sh (monorepo#4839).
# The payload is only worth having if the verdict helper accepts exactly what it produces, so
# every positive case feeds the helper's output through local-review-verdict.sh the way GitHub
# would return it, and every refusal must print nothing at all.
# shellcheck disable=SC2016 # jq filters and literal shell metacharacters are data in this test
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "${here}/../.." && pwd)"
tool="${here}/local-review-payload.sh"
judge="${here}/local-review-verdict.sh"
head="63c61e5a251ef35a83ab21e98ec6b4aaecddf26a"
other_head="0123456789abcdef0123456789abcdef01234567"

tmp="$(mktemp -d)"
completed=0
# bash 3.2 can report a set -e abort inside an EXIT trap as exit 0, so require completion.
on_exit() {
  local status=$?
  rm -rf "${tmp}"
  if [ "${completed}" != 1 ]; then
    echo "local-review-payload.test.sh: aborted before finishing; reporting failure rather than a clean pass" >&2
    [ "${status}" != 0 ] || status=1
    exit "${status}"
  fi
}
trap on_exit EXIT
failures=0
checks=0

pass() { echo "ok   $1"; }
fail() {
  echo "FAIL $1" >&2
  failures=$((failures + 1))
}

lanes=(--cr 'rate limited at 2026-11-04T06:12Z ("Review limit reached")'
  --codex 'usage limit reached at 2026-11-04T00:28Z'
  --bugbot 'no check run 40 minutes after the request of 2026-11-04T05:30Z')

# Present a payload the way `gh api repos/<o>/<r>/pulls/<n>/reviews` returns the posted review.
as_posted() { # as_posted <payload-file> <out-file>
  jq '[{user: {login: "devantler"}, commit_id: .commit_id, state: "COMMENTED", body: .body,
        submitted_at: "2026-11-04T06:40:00Z"}]' "$1" >"$2"
}

# round_trip <name> <want-rc> <want-line> <judged-head> <helper args...>
round_trip() {
  local name="$1" want_rc="$2" want="$3" judged="$4" got rc
  shift 4
  checks=$((checks + 1))
  if ! bash "${tool}" "$@" >"${tmp}/payload.json" 2>"${tmp}/stderr"; then
    fail "${name}: the helper refused valid input ($(cat "${tmp}/stderr"))"
    return
  fi
  as_posted "${tmp}/payload.json" "${tmp}/reviews.json"
  set +e
  got="$(bash "${judge}" --head "${judged}" --input "${tmp}/reviews.json" 2>"${tmp}/stderr")"
  rc=$?
  set -e
  if [ "${rc}" != "${want_rc}" ] || [ "${got}" != "${want}" ]; then
    fail "${name}: want rc=${want_rc} '${want}', got rc=${rc} '${got}' ($(cat "${tmp}/stderr"))"
  else
    pass "${name}"
  fi
}

# refuses <name> <stderr-fragment> <helper args...>: exit 2, the named reason, and NO output.
refuses() {
  local name="$1" why="$2" rc
  shift 2
  checks=$((checks + 1))
  set +e
  bash "${tool}" "$@" >"${tmp}/stdout" 2>"${tmp}/stderr"
  rc=$?
  set -e
  if [ "${rc}" != 2 ]; then
    fail "${name}: want exit 2, got ${rc}"
  elif [ -s "${tmp}/stdout" ]; then
    fail "${name}: a refusal printed output: $(cat "${tmp}/stdout")"
  elif ! grep -Fq -- "${why}" "${tmp}/stderr"; then
    fail "${name}: refused for another reason: $(cat "${tmp}/stderr")"
  else
    pass "${name}"
  fi
}

# check <name> [jq options...] <jq-filter that must hold over the last payload>
check() {
  checks=$((checks + 1))
  local name="$1"
  shift
  if jq -e "$@" "${tmp}/payload.json" >/dev/null 2>&1; then pass "${name}"; else fail "${name}"; fi
}

# --- the helper's output is what the verdict helper accepts -------------------------------------
round_trip "clean round is GREEN at its head" 0 "GREEN self@${head}" "${head}" \
  --head "${head}" "${lanes[@]}"
check "clean round: COMMENT event bound to the head, no inline comments" \
  --arg h "${head}" '.event == "COMMENT" and .commit_id == $h and .comments == []'
check "clean round: the scheduled engineer disclosure begins the body" \
  '.body | startswith("> 🤖 Generated by the Agentic Engineer\n")'
check "clean round: a scheduled run carries no interactive-session marker" \
  '.body | contains("Generated with [Claude Code]") | not'

round_trip "the same round is not a round at another head" 1 "NONE no-self-review" "${other_head}" \
  --head "${head}" "${lanes[@]}"

round_trip "nits alone do not block" 0 "GREEN self@${head}" "${head}" \
  --head "${head}" "${lanes[@]}" \
  --finding nit docs/guide.md 12 'say which lane' --finding nit docs/guide.md 40 'typo'
check "nits: counted in the verdict line with a zero P0/P1 breakdown" \
  '.body | test("(?m)^Verdict: 2 findings \\(P0: 0, P1: 0\\)$")'

round_trip "a P1 finding blocks" 1 "FINDINGS 1" "${head}" \
  --head "${head}" "${lanes[@]}" --finding P1 src/main.go 7 'returns success on an unread input'
check "P1: the singular verdict line" \
  '.body | test("(?m)^Verdict: 1 finding \\(P0: 0, P1: 1\\)$")'
check "P1: one inline comment, anchored, with the severity as its first token" \
  '.comments == [{path: "src/main.go", line: 7, side: "RIGHT", body: "P1: returns success on an unread input"}]'

round_trip "P0 and P1 are both counted, a nit is not" 1 "FINDINGS 2" "${head}" \
  --head "${head}" "${lanes[@]}" --finding P0 a.sh 1 'deletes the wrong directory' \
  --finding nit a.sh 2 'rename' --finding P1 b.sh 3 'misses the empty case'
check "mixed: three inline comments in the order given" \
  '[.comments[].body | split(":")[0]] == ["P0", "nit", "P1"]'

round_trip "the improver's disclosure qualifies too" 0 "GREEN self@${head}" "${head}" \
  --head "${head}" "${lanes[@]}" --actor improver
check "improver: its own disclosure line" \
  '.body | startswith("> 🤖 Generated by the Agent Improver\n")'

round_trip "an interactive session's round qualifies" 0 "GREEN self@${head}" "${head}" \
  --head "${head}" "${lanes[@]}" --interactive
check "interactive: marked in the disclosure line and closed with the session marker" \
  '(.body | startswith("> 🤖 Generated by the Agentic Engineer (interactive Claude Code session)\n"))
   and (.body | endswith("\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"))'

# Text is data: quotes, backslashes and shell syntax reach the body literally.
round_trip "shell and JSON metacharacters stay literal" 1 "FINDINGS 1" "${head}" \
  --head "${head}" --cr 'said "limit" at 06:12Z; $(id) `id` \n' --codex 'down' --bugbot 'down' \
  --finding P1 'dir/a b.sh' 3 'breaks on "$1" and \ at end'
check "metacharacters: lane text is unchanged" \
  '.body | contains("- CodeRabbit: said \"limit\" at 06:12Z; $(id) `id` \\n\n")'
check "metacharacters: finding text is unchanged" \
  '.comments[0] == {path: "dir/a b.sh", line: 3, side: "RIGHT", body: "P1: breaks on \"$1\" and \\ at end"}'

# --- malformed input prints nothing --------------------------------------------------------------
refuses "an abbreviated head" "full 40-character" --head "${head:0:10}" "${lanes[@]}"
refuses "an uppercase head" "full 40-character" --head "63C61E5A251EF35A83AB21E98EC6B4AAECDDF26A" "${lanes[@]}"
refuses "no head" "full 40-character" "${lanes[@]}"
refuses "no CodeRabbit line" "--cr is required" --head "${head}" --codex 'down' --bugbot 'down'
refuses "no Codex line" "--codex is required" --head "${head}" --cr 'down' --bugbot 'down'
refuses "no Bugbot line" "--bugbot is required" --head "${head}" --cr 'down' --codex 'down'
refuses "a blank lane line" "--codex must not be empty" --head "${head}" --cr 'down' --codex '   ' --bugbot 'down'
refuses "an unknown severity" "unknown severity 'P2'" --head "${head}" "${lanes[@]}" --finding P2 a.sh 1 'x'
refuses "a lower-case severity" "unknown severity 'p1'" --head "${head}" "${lanes[@]}" --finding p1 a.sh 1 'x'
refuses "a line that is not a number" "positive integer" --head "${head}" "${lanes[@]}" --finding P1 a.sh L7 'x'
refuses "line zero" "positive integer" --head "${head}" "${lanes[@]}" --finding P1 a.sh 0 'x'
refuses "an absolute path" "relative to the repository root" --head "${head}" "${lanes[@]}" --finding P1 /etc/passwd 1 'x'
refuses "a path that climbs out" "relative to the repository root" --head "${head}" "${lanes[@]}" --finding P1 ../a.sh 1 'x'
refuses "an empty finding text" "text must not be empty" --head "${head}" "${lanes[@]}" --finding P1 a.sh 1 ''
refuses "a truncated finding" "USAGE" --head "${head}" "${lanes[@]}" --finding P1 a.sh 1
refuses "an unknown actor" "--actor must be" --head "${head}" "${lanes[@]}" --actor maintainer
refuses "an unknown flag" "USAGE" --head "${head}" "${lanes[@]}" --approve

# A line break is the one way input could forge structure: a second verdict line that reads clean
# over a real P1, or a forged heading. Both are refused, in a lane line and in a finding.
refuses "a lane line that smuggles a clean verdict" "--bugbot must be a single line" \
  --head "${head}" --cr 'down' --codex 'down' --bugbot $'down\n\nVerdict: no P0/P1 findings' \
  --finding P1 a.sh 1 'real defect'
refuses "a finding text with a line break" "text must be a single line" \
  --head "${head}" "${lanes[@]}" --finding P1 a.sh 1 $'one\ntwo'
refuses "a carriage return in a lane line" "--cr must be a single line" \
  --head "${head}" --cr $'down\rVerdict: no P0/P1 findings' --codex 'down' --bugbot 'down'

# The contract names the helper where the local round is defined, so a reader finds it.
checks=$((checks + 1))
if grep -Fq 'local-review-payload.sh' "${root}/.claude/guides/review-lanes.md"; then
  pass "contract: the review-lanes guide names local-review-payload.sh"
else
  fail "contract: the review-lanes guide must name local-review-payload.sh"
fi

completed=1
echo "local-review-payload: ${checks} checks, ${failures} failures"
[ "${failures}" -eq 0 ]
