#!/usr/bin/env bash
# Seed and check agent-authored pull-request bodies at the write boundary.
#
# `check` enforces only the three safety rules (monorepo#5049). Body style is
# left to the PR template and to review:
#   1. the leading AI-disclosure line for the acting routine role;
#   2. exactly one issue relationship (or the explicit trivial-fix marker);
#   3. no non-public hostname or private IPv4 address anywhere in the raw body,
#      including link targets and HTML comments. Secret scanning does not cover
#      hostnames, and an internal name must never reach a public artifact.
# Third-party targets get only rule 3: their own policy decides the rest.

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

fail() {
  echo "pr-body contract: FAIL — $*" >&2
  exit 1
}

usage() {
  cat >&2 <<'USAGE'
Usage:
  pr-body-contract.sh seed --repo OWNER/REPO --output FILE [--role agentic-engineer|agent-improver]
  pr-body-contract.sh check --repo OWNER/REPO --body-file FILE|- [--role agentic-engineer|agent-improver] [--allow-no-issue]

seed fetches the repository's own default pull-request template, falling back to
OWNER/.github. For devantler-tech targets it prepends the canonical role disclosure;
for third-party targets it preserves the target template without suite attribution.
check enforces the disclosure line, exactly one issue relationship and the
non-public hostname rule; it makes no GitHub request.
--allow-no-issue is reserved for the consumer contract's explicit trivial-fix
carve-out; replace the seeded issue placeholder with the exact visible line
"No issue: trivial fix." before using it.
USAGE
  exit 2
}

command_name="${1:-}"
[ -n "${command_name}" ] || usage
shift

repo=''
output=''
role='agentic-engineer'
body_file=''
allow_no_issue=0

while [ "$#" -gt 0 ]; do
  case "$1" in
    --repo)
      [ "$#" -ge 2 ] || usage
      repo="$2"
      shift 2
      ;;
    --output)
      [ "$#" -ge 2 ] || usage
      output="$2"
      shift 2
      ;;
    --role)
      [ "$#" -ge 2 ] || usage
      role="$2"
      shift 2
      ;;
    --body-file)
      [ "$#" -ge 2 ] || usage
      body_file="$2"
      shift 2
      ;;
    --allow-no-issue)
      allow_no_issue=1
      shift
      ;;
    *) usage ;;
  esac
done

case "${repo}" in
  */*) ;;
  *) fail "--repo must be OWNER/REPO" ;;
esac

case "${role}" in
  agentic-engineer) disclosure='> 🤖 Generated by the Agentic Engineer' ;;
  agent-improver) disclosure='> 🤖 Generated by the Agent Improver' ;;
  *) fail "unsupported --role: ${role} (use agentic-engineer or agent-improver)" ;;
esac

work_dir="$(mktemp -d)"
canonical_repo=""
# Bash 3.2 reports a `set -u` abort to an EXIT trap as status 0, and the trap's own successful
# cleanup then becomes the script's status. Completion is recorded explicitly, so reaching a
# verdict is the only way a zero status leaves this script; an abort reports UNKNOWN (monorepo#3414).
pr_body_contract_finished=0
# shellcheck disable=SC2329 # Invoked indirectly by the EXIT trap.
pr_body_contract_cleanup() {
  local rc=$?
  rm -rf "${work_dir}"
  if [ "$pr_body_contract_finished" != 1 ] && [ "$rc" -eq 0 ]; then
    echo "pr-body contract: aborted before finishing; reporting UNKNOWN rather than a clean pass" >&2
    rc=2
  fi
  exit "$rc"
}
trap pr_body_contract_cleanup EXIT

strip_comments() {
  awk '
    function unescaped_comment_start(text, offset, relative, position, slashes, index_before) {
      offset = 1
      while (offset <= length(text)) {
        relative = index(substr(text, offset), "<!--")
        if (relative == 0) { return 0 }
        position = offset + relative - 1
        slashes = 0
        index_before = position - 1
        while (index_before > 0 && substr(text, index_before, 1) == "\\") {
          slashes++
          index_before--
        }
        if (slashes % 2 == 0) { return position }
        offset = position + 4
      }
      return 0
    }

    {
      sub(/\r$/, "")
      line = $0
      output = ""
      while (1) {
        if (in_comment) {
          comment_end = index(line, "-->")
          if (comment_end == 0) {
            line = ""
            break
          }
          line = substr(line, comment_end + 3)
          in_comment = 0
          continue
        }

        comment_start = unescaped_comment_start(line)
        if (comment_start == 0) {
          output = output line
          line = ""
          break
        }
        output = output substr(line, 1, comment_start - 1)
        line = substr(line, comment_start + 4)
        in_comment = 1
      }

      if (output ~ /^[[:space:]]*[-*+][[:space:]]+\[[ xX]\]/) {
        sub(/\[[xX]\]/, "[ ]", output)
      }
      sub(/[[:space:]]+$/, "", output)
      if (!in_comment || length(output) > 0) {
        print output
      }
    }
  ' "$1"
}


lookup_cause() {
  local error_file="$1"
  if grep -Eqi '(rate limit|HTTP 429)' "${error_file}"; then
    echo 'request-budget: the GitHub request budget is exhausted; retry after it resets'
  elif grep -Eq '(HTTP (401|403|404)|Not Found)' "${error_file}"; then
    echo 'access: GitHub refused access or did not find it'
  else
    echo 'transport: no usable answer from GitHub (connection or server error)'
  fi
}

fetch_raw() {
  local source_repo="$1"
  local source_path="$2"
  local destination="$3"
  local error_file="${work_dir}/gh-api-error"

  if gh api \
    -H 'Accept: application/vnd.github.raw+json' \
    "repos/${source_repo}/contents/${source_path}" \
    >"${destination}" 2>"${error_file}"; then
    [ -s "${destination}" ] ||
      fail "template lookup returned empty content for ${source_repo}/${source_path}"
    return 0
  fi

  if grep -Eq '(HTTP 404|Not Found)' "${error_file}"; then
    return 1
  fi
  fail "template lookup failed for ${source_repo}/${source_path} — $(lookup_cause "${error_file}")"
}

discovered_path=''
find_template_path() {
  local source_repo="$1"
  local source_directory="$2"
  local endpoint="repos/${source_repo}/contents"
  local listing="${work_dir}/template-directory-listing"
  local matches="${work_dir}/template-directory-matches"
  local error_file="${work_dir}/gh-api-error"
  local match_count

  if [ "${source_directory}" != '.' ]; then
    endpoint="${endpoint}/${source_directory}"
  fi
  if ! gh api "${endpoint}" --jq '.[] | select(.type == "file") | .name' \
    >"${listing}" 2>"${error_file}"; then
    if grep -Eq '(HTTP 404|Not Found)' "${error_file}"; then
      return 1
    fi
    fail "template directory lookup failed for ${source_repo}/${source_directory} — $(lookup_cause "${error_file}")"
  fi

  awk 'tolower($0) ~ /^pull_request_template[.](md|txt)$/ { print }' \
    "${listing}" >"${matches}"
  match_count="$(wc -l <"${matches}" | tr -d '[:space:]')"
  [ "${match_count}" -le 1 ] ||
    fail "template lookup is ambiguous for ${source_repo}/${source_directory}"
  [ "${match_count}" -eq 1 ] || return 1
  IFS= read -r discovered_path <"${matches}"
  if [ "${source_directory}" != '.' ]; then
    discovered_path="${source_directory}/${discovered_path}"
  fi
}

resolve_template() {
  local target_repo="$1"
  local destination="$2"
  local owner="${target_repo%%/*}"
  local directory
  local error_file="${work_dir}/gh-api-error"

  if ! canonical_repo="$(gh api "repos/${target_repo}" --jq '.full_name' \
    2>"${error_file}")"; then
    case "$(lookup_cause "${error_file}")" in
      access:*) fail "target repository is not accessible: ${target_repo}" ;;
      *) fail "target repository lookup failed for ${target_repo} — $(lookup_cause "${error_file}")" ;;
    esac
  fi
  case "${canonical_repo}" in
    */*) ;;
    *) fail "target repository returned an invalid canonical name: ${target_repo}" ;;
  esac

  for directory in '.github' '.' 'docs'; do
    if find_template_path "${target_repo}" "${directory}"; then
      fetch_raw "${target_repo}" "${discovered_path}" "${destination}" ||
        fail "discovered template disappeared for ${target_repo}/${discovered_path}"
      return 0
    fi
  done

  for directory in '.github' '.' 'docs'; do
    if find_template_path "${owner}/.github" "${directory}"; then
      fetch_raw "${owner}/.github" "${discovered_path}" "${destination}" ||
        fail "discovered template disappeared for ${owner}/.github/${discovered_path}"
      return 0
    fi
  done

  fail "no effective GitHub pull request template found for ${target_repo} or ${owner}/.github"
}

# Rule 1: the first line is the acting role's disclosure, and the body carries no second one.
check_disclosure() {
  local body="$1"
  local visible="$2"
  local first_line
  local disclosure_count

  IFS= read -r first_line <"${body}" || fail "body is empty"
  first_line="${first_line%$'\r'}"
  [ "${first_line}" = "${disclosure}" ] ||
    fail "first-line disclosure does not match --role ${role}"
  disclosure_count="$(awk -f "${script_dir}/markdown-structural-lines.awk" "${visible}" |
    grep -Ec '^(🤖[[:space:]]*)?Generated by the (Agentic Engineer|Agent Improver|Daily AI Engineer|Daily AI Assistant)([^[:alnum:]]|$)' || true)"
  [ "${disclosure_count}" -eq 1 ] ||
    fail "body must contain exactly one routine-role disclosure"
}

# Rule 2: exactly one issue relationship. A delivery may pair one Fixes with one distinct
# Part of (an experiment); any other closing keyword anywhere would close a second issue.
check_relationship() {
  local visible="$1"
  local issue_count fixes_count part_of_count marker_count no_issue_count

  if grep -Eq '^(Fixes|Part of) #[[:space:]]*$' "${visible}"; then
    fail "body contains an unresolved issue placeholder"
  fi
  issue_count="$(grep -Ec '^(Fixes|Part of) #[1-9][0-9]*$' "${visible}" || true)"
  fixes_count="$(grep -Ec '^Fixes #[1-9][0-9]*$' "${visible}" || true)"
  part_of_count="$(grep -Ec '^Part of #[1-9][0-9]*$' "${visible}" || true)"
  marker_count="$({ grep -Eio '(^|[^[:alnum:]_])(close|closes|closed|fix|fixes|fixed|resolve|resolves|resolved)[[:space:]]*:?[[:space:]]*(#|[[:alnum:]_.-]+/[[:alnum:]_.-]+#|https?://github[.]com/[[:alnum:]_.-]+/[[:alnum:]_.-]+/issues/)|(^|[^[:alnum:]_])part[[:space:]]+of[[:space:]]*:?[[:space:]]*(#|[[:alnum:]_.-]+/[[:alnum:]_.-]+#|https?://github[.]com/[[:alnum:]_.-]+/[[:alnum:]_.-]+/issues/)' \
    "${visible}" || [ "$?" -eq 1 ]; } | wc -l | tr -d '[:space:]')"
  no_issue_count="$(grep -Fxc 'No issue: trivial fix.' "${visible}" || true)"
  case "${issue_count}:${fixes_count}:${part_of_count}" in
    1:1:0 | 1:0:1 | 2:1:1)
      [ "${marker_count}" -eq "${issue_count}" ] ||
        fail "every issue relationship marker must use the permitted shape"
      [ "${no_issue_count}" -eq 0 ] ||
        fail "the trivial-fix marker cannot accompany an issue relationship"
      if [ "${issue_count}" -eq 2 ] &&
        [ "$(sed -n 's/^Fixes #//p' "${visible}")" = "$(sed -n 's/^Part of #//p' "${visible}")" ]; then
        fail "delivery and experiment issue numbers must be distinct"
      fi
      ;;
    0:0:0)
      [ "${allow_no_issue}" -eq 1 ] ||
        fail "body must contain exactly one issue relationship: Fixes #N or Part of #N; one Fixes and one Part of experiment relationship may appear together"
      [ "${marker_count}" -eq 0 ] || fail "no-issue mode forbids relationship markers"
      [ "${no_issue_count}" -eq 1 ] ||
        fail "no-issue mode requires the explicit trivial-fix marker: No issue: trivial fix."
      ;;
    *)
      fail "body must contain exactly one issue relationship: Fixes #N or Part of #N; one Fixes and one Part of experiment relationship may appear together"
      ;;
  esac
}

# Rule 3: no non-public host and no private IPv4 address anywhere in the raw body, link targets and
# HTML comments included. In prose every dotted name must end in a public top-level domain, unless
# its last label is a common file extension (a file name, not a host); a last label of one letter
# or starting with a digit (e.g., version numbers, 1.5x) is not a host. Inside code spans and fences
# a dotted name is usually code (pkg.Func, a YAML path), so there only a private address, a
# private-network suffix, or a non-public name in host position (after :// or @, or before :port)
# is refused. Markdown escapes or character references can still disguise a name; this rule
# catches mistakes, not deliberate evasion, which review covers.
check_hostnames() {
  local body="$1"
  local public_tlds="${script_dir}/pr-body-public-tlds.txt"
  local finding

  [ -r "${public_tlds}" ] || fail "public TLD evidence is missing"
  finding="$(tr '[:upper:]' '[:lower:]' <"${body}" | awk -v public_tld_file="${public_tlds}" '
    BEGIN {
      while ((getline line < public_tld_file) > 0) {
        sub(/\r$/, "", line)
        if (line !~ /^#/ && line != "") { public[tolower(line)] = 1; loaded++ }
      }
      close(public_tld_file)
      n = split("awk bash cfg conf csv env gif go hcl ini jpeg jpg js json jsx lock log mjs mod png proto sql sum svg tf tmpl toml ts tsx txt xml yaml yml zsh", ext, " ")
      for (i = 1; i <= n; i++) { file_ext[ext[i]] = 1 }
      n = split("lan local internal intranet corp home localdomain localhost private", priv, " ")
      for (i = 1; i <= n; i++) { private_suffix[priv[i]] = 1 }
      tok = "[[:alnum:]]([[:alnum:]_-]*[[:alnum:]])?([.][[:alnum:]]([[:alnum:]_-]*[[:alnum:]])?)+"
    }
    # A private IPv4 address anywhere in the token, even behind a host-style prefix.
    function private_ip(t,   ip, part, a, b) {
      while (match(t, /[0-9]+[.][0-9]+[.][0-9]+[.][0-9]+/)) {
        ip = substr(t, RSTART, RLENGTH)
        t = substr(t, RSTART + RLENGTH)
        split(ip, part, ".")
        a = part[1] + 0; b = part[2] + 0
        if (a == 10 || a == 127 || (a == 172 && b >= 16 && b <= 31) || (a == 192 && b == 168) ||
            (a == 169 && b == 254) || (a == 100 && b >= 64 && b <= 127)) { return 1 }
      }
      return 0
    }
    # judge(token, in_code, host_position): 1 when the token must be refused.
    function judge(t, code, hostpos,   label, count, last) {
      if (private_ip(t)) { return 1 }
      if (t ~ /(^|[.])home[.]arpa$/) { return 1 }
      count = split(t, label, ".")
      last = label[count]
      if (last !~ /^[a-z][a-z0-9-]+$/) { return 0 }
      if (last in private_suffix) { return 1 }
      if (last in public) { return 0 }
      if (code) { return hostpos }
      return !(last in file_ext)
    }
    # scan(text, in_code): judge every dotted token of one stretch of text.
    function scan(s, code,   t, before, after) {
      while (found == "" && match(s, tok)) {
        t = substr(s, RSTART, RLENGTH)
        before = substr(s, 1, RSTART - 1)
        after = substr(s, RSTART + RLENGTH)
        if (judge(t, code, before ~ /(:\/\/|@)$/ || after ~ /^:[0-9]/)) { found = t }
        s = after
      }
    }
    # Never exit early: the input pipe would take SIGPIPE.
    loaded == 0 || found != "" { next }
    # A fence opens on a line of only ``` or ~~~ (plus an info string without backticks) and
    # closes only on the same character; anything else on such a line is inline code or prose.
    fence != "" && $0 ~ ("^[[:space:]]*" fence fence fence "[" fence "]*[[:space:]]*$") { fence = ""; next }
    fence != "" { scan($0, 1); next }
    /^[[:space:]]*```[^`]*$/ { fence = "`"; next }
    /^[[:space:]]*~~~/ { fence = "~"; next }
    {
      # Split the line at backticks: odd pieces are prose, even pieces are inline code.
      n = split($0, piece, "`")
      for (i = 1; i <= n; i++) { scan(piece[i], (i % 2 == 0) && (i < n || n % 2 == 1)) }
    }
    END {
      if (loaded == 0) { print "UNKNOWN: public TLD evidence is empty" }
      else if (found != "") { print found }
    }
  ')"
  case "${finding}" in
    '') ;;
    UNKNOWN:*) echo "pr-body contract: ${finding}" >&2; exit 2 ;;
    *) fail "PR body names a non-public host or private address (matched: ${finding})" ;;
  esac
}

portfolio_repo=0
case "$(printf '%s' "${repo}" | tr '[:upper:]' '[:lower:]')" in
  devantler-tech/*) portfolio_repo=1 ;;
esac

case "${command_name}" in
  seed)
    [ -n "${output}" ] || usage
    [ -z "${body_file}" ] || usage
    [ ! -e "${output}" ] || fail "refusing to overwrite existing output: ${output}"
    template_file="${work_dir}/template.md"
    resolve_template "${repo}" "${template_file}"
    case "${canonical_repo}" in
      devantler-tech/*) portfolio_repo=1 ;;
      *) portfolio_repo=0 ;;
    esac
    if [ "${portfolio_repo}" -eq 1 ]; then
      {
        printf '%s\n\n' "${disclosure}"
        cat "${template_file}"
      } >"${output}"
    else
      cat "${template_file}" >"${output}"
    fi
    ;;
  check)
    [ -z "${output}" ] || usage
    [ -n "${body_file}" ] || usage
    if [ "${body_file}" = '-' ]; then
      body_file="${work_dir}/stdin-body.md"
      cat >"${body_file}"
    fi
    [ -f "${body_file}" ] || fail "body file does not exist: ${body_file}"
    if [ "${portfolio_repo}" -eq 1 ]; then
      visible_body="${work_dir}/body-visible.md"
      strip_comments "${body_file}" >"${visible_body}"
      check_disclosure "${body_file}" "${visible_body}"
      check_relationship "${visible_body}"
    fi
    check_hostnames "${body_file}"
    ;;
  *) usage ;;
esac
pr_body_contract_finished=1
