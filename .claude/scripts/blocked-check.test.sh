#!/usr/bin/env bash
# Behaviour tests for blocked-check.sh (monorepo#5051) against a fake gh.

set -euo pipefail

subject="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/blocked-check.sh"
tmp="$(mktemp -d)"
finished=0
# bash 3.2 can report a set -e abort inside an EXIT trap as exit 0, so require completion.
on_exit() {
  local status=$?
  rm -rf "${tmp}"
  if [ "${finished}" != 1 ]; then
    echo "blocked-check.test.sh: aborted before finishing; reporting failure" >&2
    [ "${status}" != 0 ] || status=1
    exit "${status}"
  fi
}
trap on_exit EXIT

fail() {
  echo "blocked-check test: FAIL — $*" >&2
  exit 1
}

# The fake answers the issue search from $FAKE/issues.json, the PR search from $FAKE/prs.json and an
# issue-state read from $FAKE/state-<repo>-<n>; it logs every call so the test can see what was read.
cat >"${tmp}/gh" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"${FAKE}/calls"
case "$*" in
  *'is:issue label:blocked'*) [ -f "${FAKE}/issues.fail" ] && exit 1; cat "${FAKE}/issues.json" ;;
  *'is:pr label:blocked'*) cat "${FAKE}/prs.json" ;;
  *'issue(number:'*)
    for arg in "$@"; do case "${arg}" in name=*) repo="${arg#name=}" ;; number=*) n="${arg#number=}" ;; esac; done
    f="${FAKE}/state-${repo}-${n}"
    if [ -f "${f}" ]; then cat "${f}"; else echo 'GraphQL: Could not resolve to an Issue with the number of 9.' >&2; exit 1; fi
    ;;
  *) echo "unexpected: $*" >&2; exit 1 ;;
esac
EOF
chmod +x "${tmp}/gh"
export FAKE="${tmp}" BLOCKED_CHECK_GH="${tmp}/gh"

page() { printf '{"data":{"search":{"issueCount":%s,"pageInfo":{"hasNextPage":false,"endCursor":null},"nodes":%s}}}\n' "$1" "$2"; }
issue() { printf '{"number":%s,"repository":{"nameWithOwner":"o/%s"},"issueDependenciesSummary":{"blockedBy":%s,"totalBlockedBy":%s}}' "$2" "$1" "$3" "$4"; }
pr() { printf '{"number":%s,"repository":{"nameWithOwner":"o/%s"},"author":{"login":"%s"},"comments":{"totalCount":%s,"nodes":%s}}' "$2" "$1" "${5:-devantler}" "$3" "$4"; }
# comment <author> <body> [<days ago>]
comment() { jq -nc --arg a "$1" --arg b "$2" --argjson d "${3:-1}" '{author:{login:$a},body:$b,createdAt:((now - $d*86400) | strftime("%Y-%m-%dT%H:%M:%SZ"))}'; }
day() { jq -nr --argjson d "$1" '(now + $d*86400) | strftime("%Y-%m-%d")'; }
D='> 🤖 Generated by the Agentic Engineer'

run() {
  local status=0
  : >"${tmp}/calls"
  "${subject}" --org o >"${tmp}/out" 2>"${tmp}/err" || status=$?
  echo "${status}"
}
has() { grep -Fqx -- "$1" "${tmp}/out" || { cat "${tmp}/out" "${tmp}/err" >&2; fail "missing row: $1"; }; }

# Issues: open native blocker parks, all-closed strands, none is missing.
page 3 "[$(issue r 1 1 1),$(issue r 2 0 2),$(issue r 3 0 0)]" >"${tmp}/issues.json"
page 0 '[]' >"${tmp}/prs.json"
[ "$(run)" = 1 ] || fail "actionable rows must exit 1"
has 'PARKED      o/r#1  1 open native blocker(s)'
has 'STRANDED    o/r#2  all 2 native blocker(s) closed'
has 'MISSING     o/r#3'
has 'CHECKED issues=3 prs=0 parked=1 actionable=2'
# Only counts are read: the issue query never asks for a blocker's own fields.
if grep -q 'blockedBy(' "${tmp}/calls"; then fail "the check read blocker nodes, which may lie outside the portfolio"; fi

# PRs: one trusted record naming an open issue of the organisation.
page 1 "[$(issue r 1 1 1)]" >"${tmp}/issues.json"
printf 'OPEN\n' >"${tmp}/state-r-50"
printf 'CLOSED\n' >"${tmp}/state-r-51"
page 7 "[
  $(pr r 10 2 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#50'),$(comment someone 'Blocked by o/r#51')]"),
  $(pr r 11 1 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#51')]"),
  $(pr r 12 1 "[$(comment devantler 'Blocked by o/r#50')]"),
  $(pr r 13 1 "[$(comment devantler "${D}"$'\n\nBlocked by elsewhere/r#50')]"),
  $(pr r 14 2 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#50'),$(comment devantler "${D}"$'\n\nBlocked by o/r#50')]"),
  $(pr r 15 1 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#9')]"),
  $(pr r 16 1 "[$(comment devantler "${D}"$'\r\n\r\nBlocked by o/r#50\r')]")
]" >"${tmp}/prs.json"
[ "$(run)" = 1 ] || fail "PR findings must exit 1"
has 'PARKED      o/r#10  o/r#50'
has 'STRANDED    o/r#11  o/r#51'
has 'MISSING     o/r#12'
has 'MISSING     o/r#13'
has 'DUPLICATE   o/r#14'
has 'MISSING     o/r#15  (record names o/r#9, which is not an issue)'
has 'PARKED      o/r#16  o/r#50'


# Dependency-bot PRs parked over 14 days need a current route: a Re-check date within 14 days.
page 0 '[]' >"${tmp}/issues.json"
page 4 "[
  $(pr r 20 1 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#50' 20)]" 'dependabot'),
  $(pr r 21 1 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#50\nRe-check '"$(day 3)" 20)]" 'renovate[bot]'),
  $(pr r 22 1 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#50\nRe-check '"$(day -1)" 20)]" 'dependabot'),
  $(pr r 23 1 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#50' 20)]" 'devantler')
]" >"${tmp}/prs.json"
[ "$(run)" = 1 ] || fail "a stranded bot PR must exit 1"
has 'STRANDED    o/r#20  o/r#50 (no current route, parked 20d)'
has 'PARKED      o/r#21  o/r#50'
has 'STRANDED    o/r#22  o/r#50 (no current route, parked 20d)'
has 'PARKED      o/r#23  o/r#50'

# Clean: exit 0.
page 1 "[$(issue r 1 1 1)]" >"${tmp}/issues.json"
page 1 "[$(pr r 10 1 "[$(comment devantler "${D}"$'\n\nBlocked by o/r#50')]")]" >"${tmp}/prs.json"
[ "$(run)" = 0 ] || fail "a clean sweep must exit 0"
has 'CHECKED issues=1 prs=1 parked=2 actionable=0'

# Fail closed: a failed search, a short read, a missing summary, an unreadable state, a long thread.
touch "${tmp}/issues.fail"
[ "$(run)" = 2 ] || fail "a failed search must be UNKNOWN"
rm "${tmp}/issues.fail"
page 2 "[$(issue r 1 1 1)]" >"${tmp}/issues.json"
[ "$(run)" = 2 ] || fail "a short read must be UNKNOWN"
page 1 '[{"number":1,"repository":{"nameWithOwner":"o/r"},"issueDependenciesSummary":null}]' >"${tmp}/issues.json"
[ "$(run)" = 2 ] || fail "a missing dependency summary must be UNKNOWN"
page 1001 '[]' >"${tmp}/issues.json"
[ "$(run)" = 2 ] || fail "over 1000 results must be UNKNOWN"
page 1 "[$(issue r 1 1 1)]" >"${tmp}/issues.json"
cat >"${tmp}/gh2" <<'EOF'
#!/usr/bin/env bash
case "$*" in
  *'issue(number:'*) echo 'HTTP 502' >&2; exit 1 ;;
  *) exec "${FAKE}/gh" "$@" ;;
esac
EOF
chmod +x "${tmp}/gh2"
BLOCKED_CHECK_GH="${tmp}/gh2" "${subject}" --org o >/dev/null 2>&1 && fail "an unreadable blocker state must not pass"
status=0; BLOCKED_CHECK_GH="${tmp}/gh2" "${subject}" --org o >/dev/null 2>&1 || status=$?
[ "${status}" = 2 ] || fail "an unreadable blocker state must be UNKNOWN, got ${status}"
page 1 "[$(pr r 10 101 '[]')]" >"${tmp}/prs.json"
[ "$(run)" = 2 ] || fail "a thread longer than one page must be UNKNOWN"

# Usage.
status=0; "${subject}" >/dev/null 2>&1 || status=$?
[ "${status}" = 2 ] || fail "a missing --org must be a usage error"
status=0; "${subject}" --org 'o/../x' >/dev/null 2>&1 || status=$?
[ "${status}" = 2 ] || fail "a malformed org must be a usage error"

finished=1
echo "blocked-check.test.sh: PASS"
