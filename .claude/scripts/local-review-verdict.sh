#!/usr/bin/env bash
# local-review-verdict.sh — decide whether a PR's review objects carry a qualifying clean LOCAL
# REVIEW ROUND for ONE exact head (monorepo#2697).
#
# WHY THIS EXISTS
#   AGENTS.md (*Local review round*) makes an agent's own posted review a green-review satisfier,
#   reported `green_review=self@<sha>`, when no review lane will deliver at the head. The surveyor
#   applied that rule by eye and missed a valid round on platform#3001 (2026-08-06): the digest
#   reported the PR blocked solely on the review gate while a clean round sat at its head. The
#   same PR also carries empty `devantler` review objects (reply containers), so "a devantler
#   review at the head" is not evidence either. This helper applies the whole shape test.
#
# USAGE
#   local-review-verdict.sh --head <40-hex-sha> [--input <file>|-]
#
#   --head   the FULL 40-character headRefOid (abbreviations are refused).
#   --input  the PR's review objects as returned by `gh api repos/<o>/<r>/pulls/<n>/reviews
#            --paginate` (default: stdin). Several concatenated pages are accepted. The caller
#            still owns the PR-class bind: a local round never qualifies on an EXTERNAL
#            contributor's PR, and this helper does not see who authored the PR.
#
# OUTPUT (one line on stdout)
#   GREEN self@<head>   the newest self-review at the head is clean and fully shaped
#   FINDINGS <n>        the newest self-review at the head reports <n> findings
#   NONE <reason>       no qualifying round at this head; <reason> is one of
#                       no-self-review, no-disclosure, missing-lane:<lane>, no-verdict
#
#   A self-review is a review object authored by `devantler` whose commit_id equals --head and
#   whose body carries a `## Self-review (fallback` heading. It qualifies only when its body
#   also begins with the `> 🤖 Generated by the` disclosure, carries a list line for EACH of
#   CodeRabbit, Codex and Cursor Bugbot, and states `Verdict: no P0/P1 findings`.
#
# EXIT CODES
#   0  GREEN
#   1  FINDINGS or NONE — the gate is not satisfied by a local round
#   2  usage error or unreadable/unparseable input — nothing was judged
set -euo pipefail

usage() {
  sed -n '13,36p' "$0" >&2
  exit 2
}

head=""
input="-"
while [ "$#" -gt 0 ]; do
  case "$1" in
    --head)
      [ "$#" -ge 2 ] || usage
      head="$2"
      shift 2
      ;;
    --input)
      [ "$#" -ge 2 ] || usage
      input="$2"
      shift 2
      ;;
    -h | --help) usage ;;
    *) usage ;;
  esac
done

grep -Eq '^[0-9a-f]{40}$' <<<"$head" || {
  echo "local-review-verdict: --head must be a full 40-character lowercase sha" >&2
  exit 2
}

if [ "$input" = "-" ]; then
  raw="$(cat)" || exit 2
else
  [ -r "$input" ] || {
    echo "local-review-verdict: cannot read $input" >&2
    exit 2
  }
  raw="$(cat -- "$input")" || exit 2
fi

# Newest self-review at the head. An unparseable input is exit 2, never "no review found".
body="$(jq -rs --arg h "$head" '
  [ .[] | if type == "array" then .[] else . end ]
  | map(select(type == "object"
      and (.user.login // "") == "devantler"
      and (.commit_id // "") == $h
      and ((.body // "") | test("(?m)^##[ \t]+Self-review \\(fallback"))))
  | sort_by(.submitted_at // "")
  | if length == 0 then "" else last.body end
' <<<"$raw")" || {
  echo "local-review-verdict: input is not a JSON array of review objects" >&2
  exit 2
}

verdict() {
  printf '%s\n' "$1"
  case "$1" in GREEN*) exit 0 ;; *) exit 1 ;; esac
}

[ -n "$body" ] || verdict "NONE no-self-review"

# The disclosure must BEGIN the body: it is what marks this as agent output, not maintainer text.
first_line="$(sed -n '/[^[:space:]]/{p;q;}' <<<"$body")"
case "$first_line" in
  '> 🤖 Generated by the '*) ;;
  *) verdict "NONE no-disclosure" ;;
esac

# The fallback is invalid without evidence for every lane.
for lane in "CodeRabbit" "Codex" "Cursor Bugbot"; do
  grep -Eq "^[[:space:]]*[-*][[:space:]]+(\*\*)?${lane}(\*\*)?([^[:alnum:]]|$)" <<<"$body" ||
    verdict "NONE missing-lane:${lane// /-}"
done

findings="$(sed -nE '/^Verdict:[[:space:]]+[0-9]+[[:space:]]+findings?/{s/^Verdict:[[:space:]]+([0-9]+).*/\1/p;q;}' <<<"$body")"
if [ -n "$findings" ] && [ "$findings" -gt 0 ]; then
  verdict "FINDINGS $findings"
fi
grep -Eq '^Verdict:[[:space:]]+no P0/P1 findings[[:space:]]*$' <<<"$body" || verdict "NONE no-verdict"

verdict "GREEN self@${head}"
